package lint

import "github.com/fantasim/canonlang/internal/types"

// The words of a fix request's path (API.md E27): `<pkg>:<Rec>.<field>`, or `<pkg>:<Variant>.<case>.<field>`.
const (
	packageMark = ":"
	pathDot     = "."
)

// fmtCancelled wraps the context error of a lint stopped at a package.
const fmtCancelled = "lint %s: %w"

// maxFileLines is the size past which a file held by one let is reported (API.md §5.7, rule L8).
const maxFileLines = 5000

// The words of CODEGEN.md §2.4's markers, which a string literal must not hold (API.md §5.7, rule L6).
const (
	markerGo   = "Code generated by canon"
	markerText = "GENERATED by canon"
)

// prefixRule is a legacy type prefix: the kinds of field type it is read for, none for any type, and
// whether a lower-case letter may follow it (`m_`), the capital of the others being what ends the prefix.
type prefixRule struct {
	prefix  string
	kinds   []types.Kind
	anyCase bool
}

// prefixRules are the prefixes of API.md §5.7, rule L2, longest first within a first letter.
var prefixRules = []prefixRule{
	{prefix: "dw"},
	{prefix: "sz"},
	{prefix: "lp"},
	{prefix: "str"},
	{prefix: "n", kinds: []types.Kind{types.Int, types.Enum, types.Ref}},
	{prefix: "w", kinds: []types.Kind{types.Int, types.Enum, types.Ref}},
	{prefix: "i", kinds: []types.Kind{types.Int, types.Enum, types.Ref}},
	{prefix: "u", kinds: []types.Kind{types.Int, types.Enum, types.Ref}},
	{prefix: "f", kinds: []types.Kind{types.Float}},
	{prefix: "b", kinds: []types.Kind{types.Bool, types.Int}},
	{prefix: "m_", anyCase: true},
}

// markers are the words a string literal holding is reported for.
var markers = []string{markerGo, markerText}
