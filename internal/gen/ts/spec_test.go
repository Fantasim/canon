const (
	codegenSpec     = "../../../spec/CODEGEN.md"
	conformanceSpec = "../../../spec/CONFORMANCE.md"
	helperFile      = "runtime/helpers.ts.txt"
	helperHeading   = "### 8.2 Helper block"
	templateHeading = "The TS template, for the same package"
	fenceOpen       = "```ts\n"
	fenceClose      = "\n```\n"
)

// fenced is the first ```ts block after heading in a spec document.
func fenced(t *testing.T, doc, heading string) string {
	t.Helper()
	data, err := os.ReadFile(doc)
	if err != nil {
		t.Fatal(err)
	}
	text := string(data)
	i := strings.Index(text, heading)
	if i < 0 {
		t.Fatalf("%s has no %q", doc, heading)
	}
	rest := text[i:]
	start := strings.Index(rest, fenceOpen)
	end := strings.Index(rest[start+len(fenceOpen):], fenceClose)
	if start < 0 || end < 0 {
		t.Fatalf("%s: no ts block after %q", doc, heading)
	}
	return rest[start+len(fenceOpen) : start+len(fenceOpen)+end+1]
}

// CODEGEN.md §8.2: the helper block is normative text; the embedded copy is the spec's, byte for byte.
func TestHelperBlockIsTheSpecs(t *testing.T) {
	want := fenced(t, codegenSpec, helperHeading)
	got, err := os.ReadFile(helperFile)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Errorf("%s differs from CODEGEN.md §8.2", helperFile)
	}
}

// CODEGEN.md §8.2: a file holds the helpers it uses, in the spec's order and with its exact text, and no others: the lines of its helper block are a subsequence of the spec's, banners included.
func TestHelperBlockIsASubsequenceOfTheSpecs(t *testing.T) {
	spec := strings.Split(strings.TrimSuffix(fenced(t, codegenSpec, helperHeading), "\n"), "\n")
	for _, f := range generatedFiles(t) {
		if strings.HasSuffix(f.Path, ".conformance.test.ts") {
			continue
		}
		block := helperBlockOf(string(f.Content))
		if len(block) == 0 {
			t.Errorf("%s: no helper block", f.Path)
			continue
		}
		next := 0
		for _, line := range block {
			for next < len(spec) && spec[next] != line {
				next++
			}
			if next == len(spec) {
				t.Errorf("%s: %q is not in the spec's block, or out of its order", f.Path, line)
				break
			}
			next++
		}
	}
}

// helperBlockOf is the lines from the first banner to the second, blank lines left out.
func helperBlockOf(src string) []string {
	var out []string
	banners := 0
	for _, line := range strings.Split(src, "\n") {
		if strings.HasPrefix(line, "// ----") {
			banners++
		}
		if banners > 0 && line != "" {
			out = append(out, line)
		}
		if banners == 3 {
			break
		}
	}
	return out
}

// generatedFiles are every file of every testdata case.
func generatedFiles(t *testing.T) []output {
	t.Helper()
	cases, err := golden.Load("testdata/ts/*.txtar", golden.Expected(generatedTS))
	if err != nil {
		t.Fatal(err)
	}
	var out []output
	for _, c := range cases {
		out = append(out, buildWorld(t, c.Archive.Files).generate(t)...)
	}
	return out
}

// CONFORMANCE.md §7.2: the TypeScript conformance file of the potion example, `damageAt` included, is the template the spec gives, vectors and all.
func TestConformanceFileIsTheSpecsTemplate(t *testing.T) {
	want := fenced(t, conformanceSpec, templateHeading)
	cases, err := golden.Load("testdata/ts/pipeline.txtar", golden.Expected(generatedTS))
	if err != nil {
		t.Fatal(err)
	}
	var got string
	for _, f := range buildWorld(t, cases[0].Archive.Files).generate(t) {
		if strings.HasSuffix(f.Path, ".conformance.test.ts") {
			got = string(f.Content)
		}
	}
	if got != want {
		t.Errorf("the conformance file differs from CONFORMANCE.md §7.2\n--- want\n%s\n--- got\n%s", want, got)
	}
}

// CODEGEN.md §2.1: TypeScript `embedded` produces exactly the `baked` output.
func TestEmbeddedIsBaked(t *testing.T) {
	cases, err := golden.Load("testdata/ts/embedded.txtar", golden.Expected(generatedTS))
	if err != nil {
		t.Fatal(err)
	}
	files := cases[0].Archive.Files
	embedded := buildWorld(t, files).generate(t)
	baked := make([]txtar.File, len(files))
	for i, f := range files {
		baked[i] = txtar.File{Name: f.Name, Data: []byte(strings.Replace(string(f.Data), "mode: embedded", "mode: baked", 1))}
	}
	again := buildWorld(t, baked).generate(t)
	if len(embedded) != 1 || len(again) != 1 || string(embedded[0].Content) != string(again[0].Content) {
		t.Errorf("embedded differs from baked:\n%s", embedded[0].Content)
	}
}

var markerPattern = regexp.MustCompile(`^// GENERATED by canon from [a-z0-9_/]+/\. DO NOT EDIT\.$`)

// CODEGEN.md §2.4, §2.5, §1.3: a generated file starts with its marker, holds at most one more comment line before its code (the conformance file's T7), and no timestamp, line number or absolute path.
func TestHeaders(t *testing.T) {
	for _, f := range generatedFiles(t) {
		lines := strings.Split(string(f.Content), "\n")
		if !markerPattern.MatchString(lines[0]) {
			t.Errorf("%s: first line %q is no marker", f.Path, lines[0])
		}
		conformance := strings.HasSuffix(f.Path, ".conformance.test.ts")
		if conformance && !strings.HasPrefix(lines[1], "// Conformance vectors of package ") {
			t.Errorf("%s: second line %q is not T7", f.Path, lines[1])
		}
		if !conformance && strings.HasPrefix(lines[1], "//") {
			t.Errorf("%s: a comment line follows the marker: %q", f.Path, lines[1])
		}
		if strings.Contains(string(f.Content), "/tmp/") || !strings.HasSuffix(string(f.Content), "\n") || strings.HasSuffix(string(f.Content), "\n\n") {
			t.Errorf("%s: a path, or not one final newline", f.Path)
		}
	}
}
