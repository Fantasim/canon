const (
	outProject = "project acme {\n  canon: \"0.1\"\n  roots {\n    out: \"out\"\n  }\n  go_module {\n    out: \"example.com/out\"\n  }\n}\n"
	jsonSource = "/// A.\npackage a\n\n/// V.\nlet v: Int = 1\n\nemit json { out: \"@out/\" }\n"
	goSource   = "/// A.\npackage a\n\n/// V.\nlet v: Int = 1\n\nemit go { out: \"@out/g\", package: \"g\", mode: baked }\n"
)

func buildTree(t *testing.T, fsys mapFS, opt build.BuildOptions) *build.BuildResult {
	t.Helper()
	p, err := build.Open(fsys, "/p", build.Options{})
	if err != nil {
		t.Fatal(err)
	}
	res, err := p.Build(context.Background(), opt)
	if err != nil {
		t.Fatal(err)
	}
	return res
}

// CODEGEN.md §2.4, WIRE.md §8.4, API.md B1, B2.
func TestMarkers(t *testing.T) {
	first := buildTree(t, mapFS{"p/project.canon": file(outProject), "p/a/a.canon": file(jsonSource)}, build.BuildOptions{})
	if len(first.Outputs) != 1 || first.Outputs[0].Path != "@out/v.json" || first.Outputs[0].Status != build.StatusWritten {
		t.Fatalf("first build: %+v", first.Outputs)
	}
	for _, c := range []struct {
		name, src, path, old string
		adopt                []string
		status               build.Status
		errors               int
	}{
		{"same content", jsonSource, "v.json", string(first.Outputs[0].Content), nil, build.StatusUnchanged, 0},
		{"json marker", jsonSource, "v.json", "\xef\xbb\xbf{\"$schema\": \"a.v@0123abcd\", \"value\": 2}", nil, build.StatusWritten, 0},
		{"json upper-case package", jsonSource, "v.json", "{\"$schema\": \"A.v@0123abcd\"}", nil, build.StatusWritten, 0},
		{"json, $schema not first", jsonSource, "v.json", "{\"value\": 2, \"$schema\": \"a.v@0123abcd\"}", nil, 0, 1},
		{"json, short hash", jsonSource, "v.json", "{\"$schema\": \"a.v@0123abc\"}", nil, 0, 1},
		{"json, unqualified", jsonSource, "v.json", "{\"$schema\": \"v@0123abcd\"}", nil, 0, 1},
		{"json, not JSON", jsonSource, "v.json", "{\"$schema\": \"a.v@0123abcd\",", nil, 0, 1},
		{"json listed in adopt", jsonSource, "v.json", "{\"v\": 1}", []string{"@out/v.json"}, 0, 1},
		{"go marker", goSource, "g/g.gen.go", "// Code generated by canon from a/. DO NOT EDIT.\r\npackage g\n", nil, build.StatusWritten, 0},
		{"C++ marker", goSource, "g/g.gen.go", "// GENERATED by canon: C++ runtime rt_v1. DO NOT EDIT.\n", nil, build.StatusWritten, 0},
		{"go, hand-written", goSource, "g/g.gen.go", "// Code generated by hand. DO NOT EDIT.\npackage g\n", nil, 0, 1},
		{"go, marker not first", goSource, "g/g.gen.go", "\n// Code generated by canon from a/. DO NOT EDIT.\n", nil, 0, 1},
	} {
		fsys := mapFS{"p/project.canon": file(outProject), "p/a/a.canon": file(c.src), "p/out/" + c.path: file(c.old)}
		res := buildTree(t, fsys, build.BuildOptions{Adopt: c.adopt})
		if res.Summary.Errors != c.errors {
			t.Errorf("%s: %d errors: %v", c.name, res.Summary.Errors, codes(res.List))
			continue
		}
		i := slices.IndexFunc(res.Outputs, func(o build.Output) bool { return o.Path == "@out/"+c.path })
		switch {
		case slices.ContainsFunc(res.Outputs, func(o build.Output) bool { return o.Status == build.StatusAdopted }):
			t.Errorf("%s: an output that is no C++ header was adopted", c.name)
		case c.errors > 0 && (res.Outputs != nil || string(fsys["p/out/"+c.path].Data) != c.old):
			t.Errorf("%s: an error build returned outputs or wrote", c.name)
		case c.errors == 0 && (i < 0 || res.Outputs[i].Status != c.status || res.Outputs[i].Abs != "/p/out/"+c.path):
			t.Errorf("%s: outputs %+v", c.name, res.Outputs)
		case c.errors == 0 && !bytes.Equal(fsys["p/out/"+c.path].Data, res.Outputs[i].Content):
			t.Errorf("%s: not written", c.name)
		}
	}
}

// CLI.md §3.4 --target, CODEGEN.md §2.3, API.md B1, DECISIONS 196.
func TestTargets(t *testing.T) {
	fsys := mapFS{"p/project.canon": file(outProject), "p/a/a.canon": file(goSource + "\nemit json { out: \"@out/\" }\n")}
	res := buildTree(t, fsys, build.BuildOptions{Targets: []ir.Target{ir.TargetJSON}})
	if len(res.Outputs) != 1 || res.Outputs[0].Target != ir.TargetJSON {
		t.Errorf("json only: %+v", res.Outputs)
	}
	res = buildTree(t, fsys, build.BuildOptions{})
	var paths []string
	for _, o := range res.Outputs {
		paths = append(paths, o.Path)
	}
	if !slices.Equal(paths, []string{"@out/g/g.gen.go", "@out/g/rt/rt.go", "@out/v.json"}) {
		t.Errorf("every target: %v", paths)
	}
	fsys["p/a/a.canon"] = file(jsonSource + "\nlet w: Int = true\n\nemit ts { out: \"@out/a.ts\" }\n")
	checked := false
	checker := func(context.Context, *project.Project, []*syntax.File, map[string]*diag.Bag) *check.Program {
		checked = true
		return nil
	}
	p, err := build.Open(fsys, "/p", build.Options{Checker: checker})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := p.Build(context.Background(), build.BuildOptions{}); !errors.Is(err, build.ErrNoGenerator) || checked {
		t.Errorf("ts: %v, analysed %t", err, checked)
	}
	res = buildTree(t, fsys, build.BuildOptions{Targets: []ir.Target{ir.TargetJSON}})
	if res.Summary.Errors == 0 || res.Outputs != nil || res.Locks != nil {
		t.Errorf("json after an error: %d errors, %+v", res.Summary.Errors, res.Outputs)
	}
}

// API.md R1, R3, O4, DECISIONS 196: a load, a cancellation, an unknown selector or layer fail the call.
func TestBuildErrors(t *testing.T) {
	ctx := context.Background()
	// M3 still refuses a load.dir match whose format is not json (DECISIONS 173, 196).
	load := "/// A.\npackage a\n\n/// V.\nlet v: [Int] = load.dir(\"x.txt\")\n"
	fsys := mapFS{"p/project.canon": file(outProject), "p/a/a.canon": file(load), "p/a/x.txt": file("1")}
	p, err := build.Open(fsys, "/p", build.Options{})
	if err != nil {
		t.Fatal(err)
	}
	_, err = p.Build(ctx, build.BuildOptions{})
	var le *build.LoadError
	if !errors.Is(err, build.ErrLoad) || !errors.As(err, &le) || le.Site.Path != "a/a.canon" || le.Site.Line != 5 || le.Site.Col != 16 {
		t.Errorf("load: %v", err)
	}
	cancelled, cancel := context.WithCancel(ctx)
	cancel()
	if _, err := p.Analyze(cancelled, nil); !errors.Is(err, context.Canceled) {
		t.Errorf("cancelled: %v", err)
	}
	if _, err := p.Build(ctx, build.BuildOptions{Packages: []string{"b"}}); err == nil {
		t.Error("unknown package: no error")
	}
	layered, err := build.Open(mapFS{"p/project.canon": file(outProject), "p/a/a.canon": file(jsonSource)}, "/p", build.Options{Layers: []string{"x"}})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := layered.Analyze(ctx, nil); !errors.Is(err, build.ErrUnknownLayer) {
		t.Errorf("unknown layer: %v", err)
	}
}
