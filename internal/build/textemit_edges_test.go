// CODEGEN.md §2.9 Migration, DECISIONS 326: a legacy manifest honoured for package a grants nothing to package b in the same directory.
func TestTextEmitLegacyPerPackage(t *testing.T) {
	fsys := twoPackages("a.txt", "x.txt")
	fsys["p/out/sql/.canon-text"] = file("# GENERATED by canon from a/. DO NOT EDIT.\na.txt\nx.txt\n")
	fsys["p/out/sql/x.txt"] = file("-- by hand")
	res := buildTree(t, fsys, build.BuildOptions{})
	if !slices.Equal(codes(res.List), []diag.Code{diag.E8001.Def().Code}) || string(fsys["p/out/sql/x.txt"].Data) != "-- by hand" {
		t.Errorf("%sb took a's legacy names: %v, %q", rule, codes(res.List), fsys["p/out/sql/x.txt"].Data)
	}
}

// failRename is a file system whose rename onto a path ending in suffix fails.
type failRename struct {
	mapFS
	suffix string
}

func (f failRename) Rename(oldname, newname string) error {
	if strings.HasSuffix(newname, f.suffix) {
		return errors.New("injected")
	}
	return f.mapFS.Rename(oldname, newname)
}

// CODEGEN.md §2.9 Migration, DECISIONS 326: the deletion of a legacy manifest is part of the all-or-nothing write.
func TestTextEmitLegacyAtomic(t *testing.T) {
	fsys := textTree(textEmit)
	fsys["p/out/sql/.canon-text"] = file(legacyOne)
	p, err := build.Open(failRename{mapFS: fsys, suffix: "a/canon.outputs"}, "/p", build.Options{})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := p.Build(context.Background(), build.BuildOptions{}); err == nil {
		t.Fatal("the injected rename error was lost")
	}
	if string(fsys["p/out/sql/.canon-text"].Data) != legacyOne || len(filesUnder(fsys, "p/out/sql/Schema")) != 0 {
		t.Errorf("%sa failed write left %v", rule, filesUnder(fsys, "p/"))
	}
}

// CODEGEN.md §2.9, DECISIONS 326: ownership follows the declared path, so --root moves the files and keeps the names.
func TestTextEmitRoots(t *testing.T) {
	fsys := textTree(textEmit)
	p, err := build.Open(fsys, "/p", build.Options{Roots: map[string]string{"out": "alt"}})
	if err != nil {
		t.Fatal(err)
	}
	for i := range 2 {
		res, err := p.Build(context.Background(), build.BuildOptions{})
		if err != nil || res.Summary.Errors != 0 {
			t.Fatalf("%sbuild %d: %v, %v", rule, i, err, codes(res.List))
		}
	}
	if string(fsys["p/a/canon.outputs"].Data) != textOutputs || len(filesUnder(fsys, "p/alt/sql/")) != 2 || len(filesUnder(fsys, "p/out/")) != 0 {
		t.Errorf("%s--root: %q, %v", rule, fsys["p/a/canon.outputs"].Data, filesUnder(fsys, "p/"))
	}
}

// CODEGEN.md §2.9, DECISIONS 326: a package with no emit text loses its marked canon.outputs (written, or stale under --check); a hand-written one stays.
func TestTextEmitStaleListingRemoved(t *testing.T) {
	fsys := textTree(textEmit)
	buildTree(t, fsys, build.BuildOptions{})
	fsys["p/a/a.canon"] = file(textSource)
	res := buildTree(t, fsys, build.BuildOptions{Check: true})
	if !res.Stale || statusOf(t, res, "a/canon.outputs") != build.StatusStale || len(fsys["p/a/canon.outputs"].Data) == 0 {
		t.Errorf("%sstale listing under --check: %+v", rule, res.Outputs)
	}
	res = buildTree(t, fsys, build.BuildOptions{})
	if _, kept := fsys["p/a/canon.outputs"]; kept || statusOf(t, res, "a/canon.outputs") != build.StatusWritten {
		t.Errorf("%sstale listing kept %v: %+v", rule, kept, res.Outputs)
	}
	fsys["p/a/canon.outputs"] = file("mine\n")
	buildTree(t, fsys, build.BuildOptions{})
	if string(fsys["p/a/canon.outputs"].Data) != "mine\n" {
		t.Errorf("%sa hand-written canon.outputs was removed", rule)
	}
}

// CODEGEN.md §2.9, DECISIONS 326: an output on a canon.lock or canon.outputs path is E8152.
