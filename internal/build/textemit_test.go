const (
	textProject = "project acme {\n  canon: \"0.1\"\n  roots {\n    out: \"out\"\n    copy: \"copy\"\n  }\n}\n"
	textSource  = "/// A.\npackage a\n\nconst VERSION = 3\n\n" +
		"/// The version.\n@text(\"_version.sql\")\nexport fn versionSql() -> String { return \"SELECT {VERSION} AS contract;\\n\" }\n\n" +
		"/// The schema, with no final newline.\n@text(\"Schema.sql\")\nexport fn schemaSql() -> String { return \"CREATE TABLE t (id INT);\" }\n\n"
	textEmit    = textSource + "emit text { out: \"@out/sql\" }\n"
	textOutputs = "# GENERATED by canon from a/. DO NOT EDIT.\n@out/sql/Schema.sql\n@out/sql/_version.sql\n"
	legacyOne   = "# GENERATED by canon from a/. DO NOT EDIT.\nSchema.sql\n_version.sql\n"
	rule        = "CODEGEN.md §2.9, DECISIONS 326: "
)

// onePackage is a package named name that writes the text file file into dir.
func onePackage(name, file, dir string) string {
	return "/// P.\npackage " + name + "\n\n/// F.\n@text(\"" + file + "\")\nexport fn f() -> String { return \"" + name + "\" }\n\nemit text { out: \"" + dir + "\" }\n"
}

// displayOf is the display path of the file at path: under a root, but canon.outputs, which sits in its package.
func displayOf(path string) string {
	return strings.Replace("@"+path, "@a/", "a/", 1)
}

// filesUnder are the files of fsys under prefix, sorted.
func filesUnder(fsys mapFS, prefix string) []string {
	var out []string
	for name := range fsys { //canon:unordered sorted below
		if strings.HasPrefix(name, prefix) {
			out = append(out, name)
		}
	}
	slices.Sort(out)
	return out
}

// textTree is a project whose package a writes two text files to @out/sql.
func textTree(src string) mapFS {
	return mapFS{"p/project.canon": file(textProject), "p/a/a.canon": file(src)}
}

// statusOf is the status of the output at display path, or fails.
func statusOf(t *testing.T, res *build.BuildResult, display string) build.Status {
	t.Helper()
	i := slices.IndexFunc(res.Outputs, func(o build.Output) bool { return o.Path == display })
	if i < 0 {
		t.Fatalf("no output %s among %+v", display, res.Outputs)
	}
	return res.Outputs[i].Status
}

// CODEGEN.md §2.9, DECISIONS 294, 326: values verbatim; canon.outputs sorted under its marker, nothing else in the directory.
func TestTextEmitWritesVerbatim(t *testing.T) {
	fsys := textTree(textEmit)
	res := buildTree(t, fsys, build.BuildOptions{})
	if res.Summary.Errors != 0 {
		t.Fatalf("errors: %v", codes(res.List))
	}
	for path, want := range map[string]string{ //canon:unordered each file is judged alone
		"out/sql/_version.sql": "SELECT 3 AS contract;\n",
		"out/sql/Schema.sql":   "CREATE TABLE t (id INT);",
		"a/canon.outputs":      textOutputs,
	} {
		if got := string(fsys["p/"+path].Data); got != want {
			t.Errorf("%s = %q, want %q", path, got, want)
		}
		if res.Outputs[slices.IndexFunc(res.Outputs, func(o build.Output) bool { return o.Path == displayOf(path) })].Target != ir.TargetText {
			t.Errorf("%s: not a text output", path)
		}
	}
	if got := filesUnder(fsys, "p/out/"); !slices.Equal(got, []string{"p/out/sql/Schema.sql", "p/out/sql/_version.sql"}) {
		t.Errorf("%sfiles in the out dir: %v", rule, got)
	}
	again := buildTree(t, fsys, build.BuildOptions{})
	if statusOf(t, again, "@out/sql/Schema.sql") != build.StatusUnchanged {
		t.Errorf("an unchanged build rewrote: %+v", again.Outputs)
	}
	fsys["p/a/a.canon"] = file(strings.Replace(textEmit, "id INT", "id BIGINT", 1))
	changed := buildTree(t, fsys, build.BuildOptions{})
	if statusOf(t, changed, "@out/sql/Schema.sql") != build.StatusWritten || string(fsys["p/out/sql/Schema.sql"].Data) != "CREATE TABLE t (id BIGINT);" {
		t.Errorf("a second build did not overwrite its own file: %+v", changed.Outputs)
	}
}

// CODEGEN.md §2.4, §2.9, DECISIONS 326: E8001 for a file no marked canon.outputs names, unless adopted; canon.outputs itself needs its marker.
func TestTextEmitOwnership(t *testing.T) {
	for _, c := range []struct {
		name, path, old string
		adopt           []string
		status          build.Status
		errors          int
	}{
		{"hand-written", "out/sql/Schema.sql", "-- mine", nil, 0, 1},
		{"adopted", "out/sql/Schema.sql", "-- mine", []string{"@out/sql/Schema.sql"}, build.StatusAdopted, 0},
		{"code marker is no ownership", "out/sql/Schema.sql", "// GENERATED by canon from a/. DO NOT EDIT.\n", nil, 0, 1},
		{"unmarked canon.outputs", "a/canon.outputs", "@out/sql/Schema.sql\n", nil, 0, 1},
		{"canon.outputs is not adoptable", "a/canon.outputs", "-- mine\n", []string{"a/canon.outputs"}, 0, 1},
		{"marked canon.outputs", "a/canon.outputs", "# GENERATED by canon from b/. DO NOT EDIT.\r\n@out/sql/old.sql\n", nil, build.StatusWritten, 0},
	} {
		fsys := textTree(textEmit)
		fsys["p/"+c.path] = file(c.old)
		res := buildTree(t, fsys, build.BuildOptions{Adopt: c.adopt})
		switch {
		case res.Summary.Errors != c.errors:
			t.Errorf("%s: %d errors: %v", c.name, res.Summary.Errors, codes(res.List))
		case c.errors > 0 && (!slices.Equal(codes(res.List), []diag.Code{diag.E8001.Def().Code}) || string(fsys["p/"+c.path].Data) != c.old):
			t.Errorf("%s: %v, %q", c.name, codes(res.List), fsys["p/"+c.path].Data)
		case c.errors == 0 && statusOf(t, res, displayOf(c.path)) != c.status:
			t.Errorf("%s: outputs %+v", c.name, res.Outputs)
		}
	}
	fsys := textTree(textEmit)
	fsys["p/a/canon.outputs"] = file("# GENERATED by canon from a/. DO NOT EDIT.\n@out/sql/Schema.sql\n")
	fsys["p/out/sql/Schema.sql"] = file("-- an older build's")
	if res := buildTree(t, fsys, build.BuildOptions{}); res.Summary.Errors != 0 || statusOf(t, res, "@out/sql/Schema.sql") != build.StatusWritten {
		t.Errorf("a listed file: %v, %+v", codes(res.List), res.Outputs)
	}
}

// CODEGEN.md §2.9, DECISIONS 297: a text file no longer written stays on disk and leaves canon.outputs.
func TestTextEmitOrphan(t *testing.T) {
	fsys := textTree(textEmit)
	buildTree(t, fsys, build.BuildOptions{})
	fsys["p/a/a.canon"] = file(strings.Replace(textEmit, "@text(\"Schema.sql\")\n", "", 1))
	res := buildTree(t, fsys, build.BuildOptions{})
	if res.Summary.Errors != 0 || slices.ContainsFunc(res.Outputs, func(o build.Output) bool { return o.Path == "@out/sql/Schema.sql" }) {
		t.Fatalf("rebuild: %v, %+v", codes(res.List), res.Outputs)
	}
	if got := string(fsys["p/out/sql/Schema.sql"].Data); got != "CREATE TABLE t (id INT);" {
		t.Errorf("the orphan was touched: %q", got)
	}
	if got := string(fsys["p/a/canon.outputs"].Data); got != "# GENERATED by canon from a/. DO NOT EDIT.\n@out/sql/_version.sql\n" {
		t.Errorf("canon.outputs = %q", got)
	}
}

// CLI.md §3.4 --check, CODEGEN.md §2.9, DECISIONS 326: a changed text file or canon.outputs is stale and nothing is written; a fresh tree is not stale.
func TestTextEmitCheck(t *testing.T) {
	fsys := textTree(textEmit)
	buildTree(t, fsys, build.BuildOptions{})
	fsys["p/out/sql/Schema.sql"] = file("-- drifted")
	res := buildTree(t, fsys, build.BuildOptions{Check: true})
	if !res.Stale || statusOf(t, res, "@out/sql/Schema.sql") != build.StatusStale || statusOf(t, res, "@out/sql/_version.sql") != build.StatusUnchanged {
		t.Errorf("check: stale %v, %+v", res.Stale, res.Outputs)
	}
	if string(fsys["p/out/sql/Schema.sql"].Data) != "-- drifted" {
		t.Error("--check wrote")
	}
	fsys["p/out/sql/Schema.sql"] = file("CREATE TABLE t (id INT);")
	if res := buildTree(t, fsys, build.BuildOptions{Check: true}); res.Stale {
		t.Errorf("%sa fresh tree is stale: %+v", rule, res.Outputs)
	}
	fsys["p/a/canon.outputs"] = file("# GENERATED by canon from a/. DO NOT EDIT.\n")
	res = buildTree(t, fsys, build.BuildOptions{Check: true})
	if !res.Stale || statusOf(t, res, "a/canon.outputs") != build.StatusStale {
		t.Errorf("%sa drifted canon.outputs: stale %v, %+v", rule, res.Stale, res.Outputs)
	}
}

// CODEGEN.md §2.1 (copies), §2.9: each entry of a list out writes the files, and one canon.outputs names them all.
func TestTextEmitCopies(t *testing.T) {
	fsys := textTree(textSource + "emit text { out: [\"@out/sql\", \"@copy/db\"] }\n")
	res := buildTree(t, fsys, build.BuildOptions{})
	if res.Summary.Errors != 0 {
		t.Fatalf("errors: %v", codes(res.List))
	}
	for _, dir := range []string{"out/sql", "copy/db"} {
		if string(fsys["p/"+dir+"/Schema.sql"].Data) != "CREATE TABLE t (id INT);" || len(filesUnder(fsys, "p/"+dir+"/")) != 2 {
			t.Errorf("%s: copy not written", dir)
		}
	}
	want := "# GENERATED by canon from a/. DO NOT EDIT.\n@copy/db/Schema.sql\n@copy/db/_version.sql\n@out/sql/Schema.sql\n@out/sql/_version.sql\n"
	if got := string(fsys["p/a/canon.outputs"].Data); got != want {
		t.Errorf("%scanon.outputs = %q", rule, got)
	}
}

// CODEGEN.md §2.9, DECISIONS 300, WIRE.md §8.1: no emit text writes nothing, and a ts emit leaves a @text fn out; a file named .canon-text is an ordinary file, kept.
func TestTextEmitElsewhere(t *testing.T) {
	fsys := textTree(textSource + "emit ts { out: \"@out/a.ts\" }\n")
	res := buildTree(t, fsys, build.BuildOptions{})
	if res.Summary.Errors != 0 || len(res.Outputs) != 1 || strings.Contains(string(res.Outputs[0].Content), "schemaSql") {
		t.Errorf("no emit text: %v, %+v", codes(res.List), res.Outputs)
	}
	clash := strings.Replace(textEmit, "\"Schema.sql\"", "\".canon-text\"", 1)
	res = buildTree(t, textTree(clash), build.BuildOptions{})
	if res.Summary.Errors != 0 || len(filesUnder(textTreeBuilt(t, clash), "p/out/sql/.canon-text")) != 1 {
		t.Errorf("a file named .canon-text: %v", codes(res.List))
	}
}

// textTreeBuilt is the tree after a build of src.
func textTreeBuilt(t *testing.T, src string) mapFS {
	t.Helper()
	fsys := textTree(src)
	buildTree(t, fsys, build.BuildOptions{})
	return fsys
}

// twoPackages is a project whose packages a and b write the files fa and fb into @out/sql.
func twoPackages(fa, fb string) mapFS {
	return mapFS{"p/project.canon": file(textProject), "p/a/a.canon": file(onePackage("a", fa, "@out/sql")), "p/b/b.canon": file(onePackage("b", fb, "@out/sql"))}
}

// CODEGEN.md §2.9, DECISIONS 326, handoff 2026-10-07 D6: two packages write different files into one directory; one path twice is E8152.
func TestTextEmitSharedDirectory(t *testing.T) {
	fsys := twoPackages("x.txt", "y.txt")
	res := buildTree(t, fsys, build.BuildOptions{})
	if res.Summary.Errors != 0 {
		t.Fatalf("%sshared dir: %v", rule, codes(res.List))
	}
	if got := filesUnder(fsys, "p/out/"); !slices.Equal(got, []string{"p/out/sql/x.txt", "p/out/sql/y.txt"}) {
		t.Errorf("%sfiles: %v", rule, got)
	}
	if string(fsys["p/b/canon.outputs"].Data) != "# GENERATED by canon from b/. DO NOT EDIT.\n@out/sql/y.txt\n" {
		t.Errorf("b/canon.outputs = %q", fsys["p/b/canon.outputs"].Data)
	}
	if again := buildTree(t, fsys, build.BuildOptions{Check: true}); again.Stale || again.Summary.Errors != 0 {
		t.Errorf("%sshared dir rebuilt: %+v", rule, again.Outputs)
	}
	if res := buildTree(t, twoPackages("x.txt", "x.txt"), build.BuildOptions{}); !slices.Contains(codes(res.List), diag.E8152.Def().Code) {
		t.Errorf("%sone path twice: %v", rule, codes(res.List))
	}
}

// CODEGEN.md §2.9 Migration, DECISIONS 326: a legacy .canon-text whose marker names the package is honoured for the build, then deleted; any other is left alone and grants nothing.
func TestTextEmitLegacyManifest(t *testing.T) {
	for _, c := range []struct {
		name, legacy string
		honoured     bool
	}{
		{"marker naming the package", legacyOne, true},
		{"marker naming another", "# GENERATED by canon from b/. DO NOT EDIT.\nSchema.sql\n", false},
		{"no marker", "Schema.sql\n", false},
	} {
		fsys := textTree(textEmit)
		fsys["p/out/sql/.canon-text"] = file(c.legacy)
		fsys["p/out/sql/Schema.sql"] = file("-- an older build's")
		res := buildTree(t, fsys, build.BuildOptions{})
		_, kept := fsys["p/out/sql/.canon-text"]
		switch {
		case c.honoured && (res.Summary.Errors != 0 || kept || string(fsys["p/out/sql/Schema.sql"].Data) != "CREATE TABLE t (id INT);"):
			t.Errorf("%s%s: %v, kept %v", rule, c.name, codes(res.List), kept)
		case !c.honoured && (!slices.Equal(codes(res.List), []diag.Code{diag.E8001.Def().Code}) || !kept):
			t.Errorf("%s%s: %v, kept %v", rule, c.name, codes(res.List), kept)
		}
	}
}

// CODEGEN.md §2.9 Migration, CLI.md §3.4 --check, DECISIONS 326: a legacy .canon-text a build would delete is a change, and --check deletes nothing.
func TestTextEmitLegacyCheck(t *testing.T) {
	fsys := textTree(textEmit)
	buildTree(t, fsys, build.BuildOptions{})
	fsys["p/out/sql/.canon-text"] = file(legacyOne)
	res := buildTree(t, fsys, build.BuildOptions{Check: true})
	if !res.Stale || statusOf(t, res, "@out/sql/.canon-text") != build.StatusStale || len(fsys["p/out/sql/.canon-text"].Data) == 0 {
		t.Errorf("%slegacy under --check: stale %v, %+v", rule, res.Stale, res.Outputs)
	}
	res = buildTree(t, fsys, build.BuildOptions{})
	if _, kept := fsys["p/out/sql/.canon-text"]; kept || statusOf(t, res, "@out/sql/.canon-text") != build.StatusWritten {
		t.Errorf("%slegacy after a build: kept %v, %+v", rule, kept, res.Outputs)
	}
}
