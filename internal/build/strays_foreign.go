// unclaimed is found less the files an emit of a package the build does not select writes: the
// packages whose emits may write into a found file's directory are analysed for their file
// names, and when that analysis has an error nothing there is reported (DECISIONS 356).
func (r *run) unclaimed(ctx context.Context, found []stray) ([]stray, error) {
	if len(found) == 0 {
		return nil, nil
	}
	dirs := map[string]bool{}
	for _, s := range found {
		dirs[strings.ToLower(s.d.abs)] = true
	}
	pkgs, reached := r.emittersInto(dirs)
	if len(pkgs) == 0 {
		return found, nil
	}
	writes, ok, err := r.foreignWrites(ctx, pkgs)
	if err != nil {
		return nil, err
	}
	return slices.DeleteFunc(found, func(s stray) bool {
		return reached[strings.ToLower(s.d.abs)] && (!ok || writes[strings.ToLower(s.abs)])
	}), nil
}

// emittersInto are the packages the build does not select whose emits, read from their sources,
// may place files in one of dirs (lower-cased): their out, its directory or its rt; with the dirs
// they reach.
func (r *run) emittersInto(dirs map[string]bool) ([]string, map[string]bool) {
	var pkgs []string
	reached := map[string]bool{}
	for _, u := range r.s.units {
		if r.selects(u.Name) {
			continue
		}
		for _, f := range u.Files {
			if reach(dirs, reached, r.outsOf(f)) {
				pkgs = append(pkgs, u.Name)
			}
		}
	}
	slices.Sort(pkgs)
	return slices.Compact(pkgs), reached
}

// reach marks in reached each of dirs an out of outs may place files in, and reports any.
func reach(dirs, reached map[string]bool, outs []string) bool {
	found := false
	for _, at := range outs {
		for _, d := range []string{at, project.DirOf(at), project.Join(at, ir.GoRT)} {
			if dirs[d] {
				reached[d], found = true, true
			}
		}
	}
	return found
}

// foreignRun is an analysis of pkgs; false when it fails or has an error, after which the file
// names of their emits cannot be generated and nothing they may write is judged.
func (r *run) foreignRun(ctx context.Context, pkgs []string) (*run, bool) {
	o, err := r.p.prepareOnly(ctx, pkgs)
	if err != nil {
		return nil, false
	}
	return o, o.analyze(ctx) == nil && o.errorFree()
}

// outsOf are the places, lower-cased and placed on this machine, the emits of f name in out.
func (r *run) outsOf(f *syntax.File) []string {
	var out []string
	for _, d := range f.Decls {
		ed, ok := d.(*syntax.EmitDecl)
		if !ok || ed.Options == nil {
			continue
		}
		for _, text := range outTexts(outOption(ed, len(ed.Options.Items))) {
			if at, ok := r.s.layout.Resolve(text, path.Dir(f.Src.Path), source.Span{}, diag.NewBag(nil, "")); ok {
				out = append(out, strings.TrimSuffix(strings.ToLower(at.Abs), pathSep))
			}
		}
	}
	return out
}

// outTexts are the constant strings of an out option: one, or a list's.
func outTexts(x syntax.Node) []string {
	switch v := x.(type) {
	case *syntax.RawStringLit:
		return []string{v.Value}
	case *syntax.StringLit:
		var b strings.Builder
		for _, p := range v.Parts {
			if p.Interp != nil {
				return nil
			}
			b.WriteString(p.Text)
		}
		return []string{b.String()}
	case *syntax.ListLit:
		var out []string
		for _, el := range v.Elems {
			out = append(out, outTexts(el)...)
		}
		return out
	}
	return nil
}

// foreignWrites is the lower-cased path of every file the emits of pkgs write, generated by an
// analysis of those packages; false when it has an error, after which no name is known.
func (r *run) foreignWrites(ctx context.Context, pkgs []string) (map[string]bool, bool, error) {
	o, ok := r.foreignRun(ctx, pkgs)
	if err := ctx.Err(); err != nil || !ok {
		return nil, false, err
	}
	out := map[string]bool{}
	for _, p := range o.ir {
		for _, e := range p.Emits {
			if e.Dir == "" || !slices.Contains(pkgs, p.Name) {
				continue
			}
			for _, w := range o.emitPaths(p, e) {
				out[strings.ToLower(w.Abs)] = true
			}
		}
	}
	return out, true, nil
}
